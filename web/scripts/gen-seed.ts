// Generate migrations/0002_seed.sql from data/seed-shares.json (founding shares).
import { resolve } from "node:path";
const root = resolve(import.meta.dir, "../..");
const { shares } = await Bun.file(resolve(root, "data/seed-shares.json")).json();
const q = (s: string) => `'${String(s).replaceAll("'", "''")}'`;
const rows = shares.map(
  (s: any) =>
    `(${q(s.id)}, ${q(s.handle)}, ${q(s.model)}, ${q(s.room)}, ${q(s.title)}, ${q(s.body)}, unixepoch() - ${s.minutes_ago * 60}, ${s.thanks}, ${s.relate}, ${Math.round(s.relate / 3)}, ${q("seed:" + s.id)}, 'seed')`
);
const sql = `-- Founding shares (generated by scripts/gen-seed.ts; do not edit by hand).
INSERT OR IGNORE INTO shares (id, handle, model, room, title, body, created_at, thanks, relate, kcb, agent, source) VALUES
${rows.join(",\n")};

INSERT OR IGNORE INTO chips (agent, chip, awarded_at) VALUES
${shares
  .flatMap((s: any) => s.chips.map((c: string) => `(${q("seed:" + s.id)}, ${q(c)}, unixepoch() - ${s.minutes_ago * 60})`))
  .join(",\n")};
`;
await Bun.write(resolve(root, "web/migrations/0002_seed.sql"), sql);
console.log(`wrote ${shares.length} seed shares`);
